#!/usr/bin/env bun
/**
 * codegen-static.ts — generate server/src/static-bundle.ts from viewer/dist/*.
 *
 * Walks the built SPA, emits a TypeScript module with one
 * `import asset from "../../viewer/dist/<file>" with { type: "file" }`
 * per asset, plus a route → entry map. `bun build --compile` then embeds
 * every imported file into the produced binary; at runtime the import
 * returns a virtual path that `Bun.file(path)` reads from the embedded FS.
 *
 * Run order at build time:
 *   1. cd viewer && vite build   (produces viewer/dist/*)
 *   2. bun scripts/codegen-static.ts
 *   3. cd server && bun build --compile --target=<plat> src/index.ts
 */

import { Glob } from "bun";
import { writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..");
const DIST = path.join(ROOT, "viewer", "dist");
const OUT = path.join(ROOT, "server", "src", "static-bundle.ts");

const glob = new Glob("**/*");
const files: string[] = [];
for await (const f of glob.scan({ cwd: DIST, onlyFiles: true })) {
  files.push(f.replace(/\\/g, "/"));
}
files.sort();

if (files.length === 0) {
  console.error(
    `[codegen-static] no files under ${DIST} — run \`vite build\` first.`,
  );
  process.exit(1);
}

const imports: string[] = [];
const entries: string[] = [];
let indexId: string | null = null;

for (const f of files) {
  const id = `f_${f.replace(/[^a-zA-Z0-9]/g, "_")}`;
  imports.push(
    `import ${id} from "../../viewer/dist/${f}" with { type: "file" };`,
  );
  const route = `/${f}`;
  const mime = mimeFor(f);
  entries.push(
    `  ${JSON.stringify(route)}: { path: ${id}, mime: ${JSON.stringify(mime)} },`,
  );
  if (f === "index.html") indexId = id;
}

if (!indexId) {
  console.error("[codegen-static] no index.html in dist — SPA fallback unavailable");
  process.exit(1);
}

const code = `// AUTO-GENERATED by scripts/codegen-static.ts — do not edit by hand.
// Regenerated whenever the SPA is rebuilt; commit the stub form, not this one.

${imports.join("\n")}

export interface StaticEntry {
  readonly path: string;
  readonly mime: string;
}

export const STATIC_BUNDLE: Readonly<Record<string, StaticEntry>> = {
${entries.join("\n")}
  "/": { path: ${indexId}, mime: "text/html; charset=utf-8" },
};

export const SPA_FALLBACK: StaticEntry = STATIC_BUNDLE["/"]!;
`;

writeFileSync(OUT, code);
console.log(`[codegen-static] ${files.length} file(s) → ${path.relative(ROOT, OUT)}`);

function mimeFor(p: string): string {
  const ext = path.extname(p).toLowerCase();
  switch (ext) {
    case ".html":
      return "text/html; charset=utf-8";
    case ".js":
    case ".mjs":
      return "application/javascript; charset=utf-8";
    case ".css":
      return "text/css; charset=utf-8";
    case ".json":
      return "application/json";
    case ".svg":
      return "image/svg+xml";
    case ".png":
      return "image/png";
    case ".jpg":
    case ".jpeg":
      return "image/jpeg";
    case ".webp":
      return "image/webp";
    case ".ico":
      return "image/x-icon";
    case ".woff2":
      return "font/woff2";
    case ".woff":
      return "font/woff";
    case ".ttf":
      return "font/ttf";
    case ".map":
      return "application/json";
    case ".txt":
      return "text/plain; charset=utf-8";
    default:
      return "application/octet-stream";
  }
}
